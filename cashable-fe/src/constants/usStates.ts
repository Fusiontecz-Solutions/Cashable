/** "NY" / "ny" → "New York"; a full name or anything else is returned trimmed. */
export function fullUsStateName(value: unknown): string {
    const v = String(value ?? "").trim();
    return US_STATE_NAME_BY_CODE[v.toUpperCase()] ?? v;
}
